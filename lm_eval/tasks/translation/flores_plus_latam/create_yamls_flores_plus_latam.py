"""
Script to generate task YAMLs for LATAM translation using FLORES+ dataset.
Based on the existing flores_gl implementation but adapted for LATAM languages.
"""

import argparse
import itertools
import yaml

# LATAM languages of interest
LATAM_LANGUAGES = [
    "spa_Latn",  # Spanish
    "por_Latn",  # Portuguese
    "eng_Latn",  # English (for reference)
    "fra_Latn",  # French (for reference)
    "ita_Latn",  # Italian (for reference)
    "deu_Latn",  # German (for reference)
    "cat_Latn",  # Catalan (for reference)
    "eus_Latn",  # Basque (for reference)
    "glg_Latn",  # Galician (for reference)
]

# Core LATAM languages (Spanish and Portuguese)
CORE_LATAM = ["spa_Latn", "por_Latn"]

# Generate all pairs: all languages <-> Spanish, all languages <-> Portuguese, Spanish <-> Portuguese
LANGUAGE_PAIRS = []

# All languages <-> Spanish
for lang in LATAM_LANGUAGES:
    if lang != "spa_Latn":
        LANGUAGE_PAIRS.append(("spa_Latn", lang))
        LANGUAGE_PAIRS.append((lang, "spa_Latn"))

# All languages <-> Portuguese  
for lang in LATAM_LANGUAGES:
    if lang != "por_Latn":
        LANGUAGE_PAIRS.append(("por_Latn", lang))
        LANGUAGE_PAIRS.append((lang, "por_Latn"))

# Spanish <-> Portuguese (already covered above, but explicit)
LANGUAGE_PAIRS.append(("spa_Latn", "por_Latn"))
LANGUAGE_PAIRS.append(("por_Latn", "spa_Latn"))

# Remove duplicates while preserving order
LANGUAGE_PAIRS = list(dict.fromkeys(LANGUAGE_PAIRS))

# Utility functions
def code_to_language_name(code):
    """Convert language code to display name."""
    code_map = {
        "spa_Latn": "Spanish",
        "por_Latn": "Portuguese", 
        "eng_Latn": "English",
        "fra_Latn": "French",
        "ita_Latn": "Italian",
        "deu_Latn": "German",
        "cat_Latn": "Catalan",
        "eus_Latn": "Basque",
        "glg_Latn": "Galician",
    }
    return code_map.get(code, code)

def code_to_short_name(code):
    """Convert language code to short name."""
    code_map = {
        "spa_Latn": "spa",
        "por_Latn": "por", 
        "eng_Latn": "eng",
        "fra_Latn": "fra",
        "ita_Latn": "ita",
        "deu_Latn": "deu",
        "cat_Latn": "cat",
        "eus_Latn": "eus",
        "glg_Latn": "glg",
    }
    return code_map.get(code, code.split("_")[0])

def jinja_var(s):
    """Wrapper to avoid having to escape { } in format strings."""
    return "{{" + s + "}}"

def doc_to_text(src: str, tgt: str) -> str:
    """Generate the input prompt template."""
    src_name = code_to_language_name(src)
    tgt_name = code_to_language_name(tgt)
    
    return f"""{src_name} sentence: {jinja_var("src_text")}
{tgt_name} sentence:"""

def doc_to_target(tgt: str) -> str:
    """Generate the target template."""
    return f"{jinja_var('tgt_text')}"

def gen_lang_yamls(output_dir: str, overwrite: bool) -> None:
    """Generate a YAML file for each translation direction."""
    
    err = []
    for src, tgt in LANGUAGE_PAIRS:
        lang_pair_name = f"{code_to_short_name(src)}-{code_to_short_name(tgt)}"
        yaml_file_name = f"flores_plus_{lang_pair_name}.yaml"
        
        # Determine the correct process_docs and doc_to_text function names
        src_short = code_to_short_name(src)
        tgt_short = code_to_short_name(tgt)
        process_docs_func = f"process_docs_{src_short}_to_{tgt_short}"
        doc_to_text_func = f"doc_to_text_{src_short}_to_{tgt_short}"
        
        try:
            with open(
                f"{output_dir}/{yaml_file_name}",
                "w" if overwrite else "x",
                encoding="utf-8",
            ) as outfile:
                print(f"Creating {yaml_file_name}...")
                outfile.write("# File generated by `create_yamls_flores_plus_latam.py`\n")
                outfile.write("include: _flores_plus_common.yaml\n")
                outfile.write(f"task: flores_plus_{lang_pair_name}\n")
                outfile.write(f"dataset_name: {src}\n")
                outfile.write(f"process_docs: !function utils.{process_docs_func}\n")
                outfile.write(f"doc_to_text: !function utils.{doc_to_text_func}\n")
                outfile.write("doc_to_target: !function utils.doc_to_target\n")
                
        except FileExistsError:
            err.append(yaml_file_name)
    
    if len(err) > 0:
        raise FileExistsError(
            "Files were not created because they already exist:"
            f" {', '.join(err)}"
            "\nUse flag --overwrite to overwrite them."
        )

def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--overwrite",
        default=False,
        action="store_true",
        help="Overwrite files if they already exist",
    )
    parser.add_argument(
        "--output-dir", default=".", help="Directory to write yaml files to"
    )
    args = parser.parse_args()
    
    gen_lang_yamls(output_dir=args.output_dir, overwrite=args.overwrite)

if __name__ == "__main__":
    main()
